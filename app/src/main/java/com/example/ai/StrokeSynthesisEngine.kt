    /**
     * Parses JSON or SVG string from AI model into ArtHaxInstructionSet
     */
    fun parseAiJsonResponse(
        rawContent: String,
        prompt: String,
        model: String
    ): ArtHaxInstructionSet? {
        // 1. Try parsing structured JSON first
        val jsonResult = parseFromJson(rawContent, prompt, model)
        if (jsonResult != null && jsonResult.strokes.isNotEmpty()) {
            return jsonResult
        }

        // 2. Try parsing SVG paths or embedded SVG vector definitions
        val svgResult = parseFromSvg(rawContent, prompt, model)
        if (svgResult != null && svgResult.strokes.isNotEmpty()) {
            return svgResult
        }

        return null
    }

    private fun parseFromJson(
        rawContent: String,
        prompt: String,
        model: String
    ): ArtHaxInstructionSet? {
        return try {
            val cleanJson = extractJsonPayload(rawContent)
            if (!cleanJson.startsWith("{") || !cleanJson.endsWith("}")) return null

            val jsonObject = JSONObject(cleanJson)
            val strokesArray = jsonObject.optJSONArray("strokes")
                ?: jsonObject.optJSONArray("paths")
                ?: jsonObject.optJSONArray("lines")
                ?: jsonObject.optJSONArray("vectors")
                ?: jsonObject.optJSONArray("elements")

            if (strokesArray == null || strokesArray.length() == 0) return null

            val strokesList = mutableListOf<DrawingStroke>()
            for (i in 0 until strokesArray.length()) {
                val item = strokesArray.getJSONObject(i)
                val color = item.optString("color", item.optString("stroke", "#00F0FF"))
                val width = item.optDouble("size", item.optDouble("width", item.optDouble("strokeWidth", 3.5))).toFloat()
                val pointsArray = item.optJSONArray("points") ?: JSONArray()
                
                val pointsList = mutableListOf<DrawingPoint>()
                for (j in 0 until pointsArray.length()) {
                    val p = pointsArray.getJSONObject(j)
                    val x = p.optDouble("x", 0.5).toFloat().coerceIn(0f, 1f)
                    val y = p.optDouble("y", 0.5).toFloat().coerceIn(0f, 1f)
                    pointsList.add(DrawingPoint(x, y))
                }

                if (pointsList.size >= 2) {
                    strokesList.add(
                        DrawingStroke(
                            id = UUID.randomUUID().toString(),
                            points = pointsList,
                            colorHex = color,
                            strokeWidth = width,
                            strokeType = StrokeType.CURVE
                        )
                    )
                }
            }

            if (strokesList.isEmpty()) null
            else ArtHaxInstructionSet(
                id = UUID.randomUUID().toString(),
                title = jsonObject.optString("title", prompt.take(24)),
                prompt = prompt,
                model = model,
                strokes = strokesList
            )
        } catch (e: Exception) {
            null
        }
    }

    /**
     * Parses SVG paths (<path d="..." stroke="...">, <polygon>, <polyline>) generated by LLMs
     * and converts cubic/quadratic bezier curves into smooth multi-point DrawingStrokes.
     */
    private fun parseFromSvg(
        rawContent: String,
        prompt: String,
        model: String
    ): ArtHaxInstructionSet? {
        return try {
            val pathRegex = Regex("""<path[^>]*d=["']([^"']+)["'][^>]*>""", RegexOption.IGNORE_CASE)
            val pathMatches = pathRegex.findAll(rawContent).toList()

            if (pathMatches.isEmpty() && !rawContent.contains("M ", ignoreCase = true) && !rawContent.contains("d=", ignoreCase = true)) {
                return null
            }

            val strokesList = mutableListOf<DrawingStroke>()
            val colorRegex = Regex("""(?:stroke|fill)=["']([^"']+)["']""", RegexOption.IGNORE_CASE)
            val widthRegex = Regex("""stroke-width=["']([^"']+)["']""", RegexOption.IGNORE_CASE)

            var minX = Float.MAX_VALUE
            var maxX = Float.MIN_VALUE
            var minY = Float.MAX_VALUE
            var maxY = Float.MIN_VALUE

            val rawParsedStrokes = mutableListOf<Triple<List<DrawingPoint>, String, Float>>()

            for (match in pathMatches) {
                val fullTag = match.value
                val dAttr = match.groupValues[1]

                val color = colorRegex.find(fullTag)?.groupValues?.get(1)?.takeIf { it != "none" && !it.startsWith("url") } ?: "#00F0FF"
                val width = widthRegex.find(fullTag)?.groupValues?.get(1)?.replace("px", "")?.toFloatOrNull() ?: 3.5f

                val points = parseSvgPathD(dAttr)
                if (points.size >= 2) {
                    points.forEach { pt ->
                        if (pt.x < minX) minX = pt.x
                        if (pt.x > maxX) maxX = pt.x
                        if (pt.y < minY) minY = pt.y
                        if (pt.y > maxY) maxY = pt.y
                    }
                    rawParsedStrokes.add(Triple(points, color, width))
                }
            }

            if (rawParsedStrokes.isEmpty()) return null

            val spanX = (maxX - minX).coerceAtLeast(0.01f)
            val spanY = (maxY - minY).coerceAtLeast(0.01f)

            // Normalize points strictly into [0.06, 0.94] canvas coordinates
            for ((points, color, width) in rawParsedStrokes) {
                val normalizedPts = points.map { pt ->
                    val normX = (0.06f + ((pt.x - minX) / spanX) * 0.88f).coerceIn(0.02f, 0.98f)
                    val normY = (0.06f + ((pt.y - minY) / spanY) * 0.88f).coerceIn(0.02f, 0.98f)
                    DrawingPoint(normX, normY)
                }

                strokesList.add(
                    DrawingStroke(
                        id = UUID.randomUUID().toString(),
                        points = normalizedPts,
                        colorHex = if (color.startsWith("#")) color else "#00F0FF",
                        strokeWidth = width.coerceIn(1.5f, 8f),
                        strokeType = StrokeType.CURVE
                    )
                )
            }

            if (strokesList.isEmpty()) null
            else ArtHaxInstructionSet(
                id = UUID.randomUUID().toString(),
                title = prompt.take(24).replaceFirstChar { it.uppercase() },
                prompt = prompt,
                model = model,
                strokes = strokesList
            )
        } catch (e: Exception) {
            null
        }
    }

    private fun parseSvgPathD(d: String): List<DrawingPoint> {
        val points = mutableListOf<DrawingPoint>()
        var curX = 0f
        var curY = 0f

        val tokens = d.replace(",", " ").replace("-", " -")
            .split(Regex("\\s+"))
            .filter { it.isNotBlank() }

        var idx = 0
        while (idx < tokens.size) {
            val token = tokens[idx]
            val cmd = token[0]

            if (cmd.isLetter()) {
                val isRelative = cmd.isLowerCase()
                val upperCmd = cmd.uppercaseChar()
                idx++

                when (upperCmd) {
                    'M', 'L' -> {
                        while (idx + 1 < tokens.size && !tokens[idx][0].isLetter()) {
                            val xVal = tokens[idx].toFloatOrNull() ?: 0f
                            val yVal = tokens[idx + 1].toFloatOrNull() ?: 0f
                            idx += 2
                            curX = if (isRelative) curX + xVal else xVal
                            curY = if (isRelative) curY + yVal else yVal
                            points.add(DrawingPoint(curX, curY))
                        }
                    }
                    'H' -> {
                        while (idx < tokens.size && !tokens[idx][0].isLetter()) {
                            val xVal = tokens[idx].toFloatOrNull() ?: 0f
                            idx++
                            curX = if (isRelative) curX + xVal else xVal
                            points.add(DrawingPoint(curX, curY))
                        }
                    }
                    'V' -> {
                        while (idx < tokens.size && !tokens[idx][0].isLetter()) {
                            val yVal = tokens[idx].toFloatOrNull() ?: 0f
                            idx++
                            curY = if (isRelative) curY + yVal else yVal
                            points.add(DrawingPoint(curX, curY))
                        }
                    }
                    'C' -> {
                        // Cubic Bezier: x1 y1 x2 y2 x y
                        while (idx + 5 < tokens.size && !tokens[idx][0].isLetter()) {
                            val x1 = tokens[idx].toFloatOrNull() ?: curX
                            val y1 = tokens[idx + 1].toFloatOrNull() ?: curY
                            val x2 = tokens[idx + 2].toFloatOrNull() ?: curX
                            val y2 = tokens[idx + 3].toFloatOrNull() ?: curY
                            val x = tokens[idx + 4].toFloatOrNull() ?: curX
                            val y = tokens[idx + 5].toFloatOrNull() ?: curY
                            idx += 6

                            val p0X = curX; val p0Y = curY
                            val p1X = if (isRelative) curX + x1 else x1
                            val p1Y = if (isRelative) curY + y1 else y1
                            val p2X = if (isRelative) curX + x2 else x2
                            val p2Y = if (isRelative) curY + y2 else y2
                            val p3X = if (isRelative) curX + x else x
                            val p3Y = if (isRelative) curY + y else y

                            // Interpolate 8 smooth intermediate curve points
                            for (step in 1..8) {
                                val t = step / 8.0f
                                val u = 1.0f - t
                                val bx = u * u * u * p0X + 3 * u * u * t * p1X + 3 * u * t * t * p2X + t * t * t * p3X
                                val by = u * u * u * p0Y + 3 * u * u * t * p1Y + 3 * u * t * t * p2Y + t * t * t * p3Y
                                points.add(DrawingPoint(bx, by))
                            }
                            curX = p3X
                            curY = p3Y
                        }
                    }
                    'Q', 'S' -> {
                        // Quadratic / Smooth Bezier
                        while (idx + 3 < tokens.size && !tokens[idx][0].isLetter()) {
                            val x1 = tokens[idx].toFloatOrNull() ?: curX
                            val y1 = tokens[idx + 1].toFloatOrNull() ?: curY
                            val x = tokens[idx + 2].toFloatOrNull() ?: curX
                            val y = tokens[idx + 3].toFloatOrNull() ?: curY
                            idx += 4

                            val p0X = curX; val p0Y = curY
                            val p1X = if (isRelative) curX + x1 else x1
                            val p1Y = if (isRelative) curY + y1 else y1
                            val p2X = if (isRelative) curX + x else x
                            val p2Y = if (isRelative) curY + y else y

                            for (step in 1..6) {
                                val t = step / 6.0f
                                val u = 1.0f - t
                                val bx = u * u * p0X + 2 * u * t * p1X + t * t * p2X
                                val by = u * u * p0Y + 2 * u * t * p1Y + t * t * p2Y
                                points.add(DrawingPoint(bx, by))
                            }
                            curX = p2X
                            curY = p2Y
                        }
                    }
                    'Z' -> {
                        if (points.isNotEmpty()) {
                            points.add(points.first())
                        }
                    }
                    else -> {}
                }
            } else {
                idx++
            }
        }

        return points
    }

    private fun extractJsonPayload(text: String): String {
        val trimmed = text.trim()
        val startIndex = trimmed.indexOf('{')
        val endIndex = trimmed.lastIndexOf('}')
        return if (startIndex != -1 && endIndex != -1 && endIndex > startIndex) {
            trimmed.substring(startIndex, endIndex + 1)
        } else {
            trimmed
        }
    }

    /**
     * Synthesizes rich vector art strokes for any prompt (presets & custom queries).
     */
    fun synthesizeArtwork(
        prompt: String,
        modelName: String = "puter-art-v1"
    ): ArtHaxInstructionSet {
        val lower = prompt.lowercase()
        val strokes = when {
            lower.contains("miku") || lower.contains("hatsune") || lower.contains("chibi") || lower.contains("sekai") -> {
                generateChibiMiku()
            }
            lower.contains("skull") || lower.contains("cyber skull") -> {
                generateCyberSkull()
            }
            lower.contains("cat") || lower.contains("neko") || lower.contains("kitten") -> {
                generateCyberCat()
            }
            lower.contains("dragon") || lower.contains("wyvern") -> {
                generateNeonDragon()
            }
            lower.contains("sakura") || lower.contains("flower") || lower.contains("blossom") -> {
                generateSakuraBlossom()
            }
            lower.contains("heart") || lower.contains("love") || lower.contains("pixel") -> {
                generateNeonPixelHeart()
            }
            lower.contains("star") || lower.contains("stellar") -> {
                generateCyberStar()
            }
            lower.contains("sunset") || lower.contains("retrowave") || lower.contains("synthwave") -> {
                generateRetroSunset()
            }
            lower.contains("sword") || lower.contains("katana") || lower.contains("blade") -> {
                generateCyberKatana()
            }
            lower.contains("mask") || lower.contains("samurai") || lower.contains("oni") -> {
                generateOniMask()
            }
            lower.contains("horror") || lower.contains("creepy") || lower.contains("eyeball") || lower.contains("eye") -> {
                generateHorrorEyeball()
            }
            lower.contains("zombie") || lower.contains("undead") || lower.contains("monster") || lower.contains("ghoul") -> {
                generateZombieHand()
            }
            lower.contains("ghost") || lower.contains("spooky") || lower.contains("phantom") || lower.contains("spirit") -> {
                generateHorrorGhost()
            }
            else -> {
                generateDynamicProceduralArt(prompt)
            }
        }

        return ArtHaxInstructionSet(
            id = UUID.randomUUID().toString(),
            title = prompt.take(30).replaceFirstChar { it.uppercase() },
            prompt = prompt,
            model = modelName,
            strokes = strokes
        )
    }

