    private fun createStarStroke(
        cx: Float,
        cy: Float,
        size: Float,
        color: String,
        width: Float
    ): DrawingStroke {
        val pts = listOf(
            DrawingPoint(cx, cy - size),
            DrawingPoint(cx + size * 0.3f, cy - size * 0.3f),
            DrawingPoint(cx + size, cy),
            DrawingPoint(cx + size * 0.3f, cy + size * 0.3f),
            DrawingPoint(cx, cy + size),
            DrawingPoint(cx - size * 0.3f, cy + size * 0.3f),
            DrawingPoint(cx - size, cy),
            DrawingPoint(cx - size * 0.3f, cy - size * 0.3f),
            DrawingPoint(cx, cy - size)
        )
        return DrawingStroke(
            id = UUID.randomUUID().toString(),
            points = pts,
            colorHex = color,
            strokeWidth = width,
            strokeType = StrokeType.LINE
        )
    }
