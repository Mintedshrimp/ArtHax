/**
 * Bounding box on screen (normalized 0.0f .. 1.0f) where target drawing canvas is located
 */
data class CalibrationBounds(
    val left: Float = 0.06f,
    val top: Float = 0.22f,
    val right: Float = 0.94f,
    val bottom: Float = 0.78f
) {
    val width: Float get() = (right - left).coerceAtLeast(0.1f)
    val height: Float get() = (bottom - top).coerceAtLeast(0.1f)
}

/**
 * Live execution state of the drawing engine
 */
sealed class ExecutionState {
    object Idle : ExecutionState()
    data class Generating(val progress: Float, val message: String) : ExecutionState()
    data class Ready(val instructionSet: ArtHaxInstructionSet) : ExecutionState()
    data class Drawing(
        val currentStrokeIndex: Int,
        val totalStrokes: Int,
        val currentPointIndex: Int,
        val totalPoints: Int,
        val progress: Float,
        val activePoint: DrawingPoint?,
        val activeColorHex: String
    ) : ExecutionState()
    object Paused : ExecutionState()
    data class Completed(val totalStrokesDrawn: Int, val durationMs: Long) : ExecutionState()
    data class Error(val message: String) : ExecutionState()
}

