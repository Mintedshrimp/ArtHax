/**
 * Normalized 2D point (0.0f .. 1.0f) relative to the target canvas bounds.
 */
data class DrawingPoint(
    val x: Float,
    val y: Float
)

/**
 * Single continuous brush stroke or line path consisting of sequential points.
 */
data class DrawingStroke(
    val id: String,
    val points: List<DrawingPoint>,
    val colorHex: String = "#00F0FF",
    val strokeWidth: Float = 4f,
    val strokeType: StrokeType = StrokeType.LINE,
    val isClosed: Boolean = false
) {
    fun parseColor(): Color {
        return try {
            val cleanHex = colorHex.removePrefix("#")
            when (cleanHex.length) {
                6 -> Color(android.graphics.Color.parseColor("#$cleanHex"))
                8 -> Color(android.graphics.Color.parseColor("#$cleanHex"))
                3 -> {
                    val r = cleanHex[0]
                    val g = cleanHex[1]
                    val b = cleanHex[2]
                    Color(android.graphics.Color.parseColor("#$r$r$g$g$b$b"))
                }
                else -> NeonCyan
            }
        } catch (e: Exception) {
            NeonCyan
        }
    }
}

enum class StrokeType {
    LINE,
    CURVE,
    DOT,
    OUTLINE,
    FILL_HATCH
}

/**
 * High-performance vector layer for organizing complex multi-part drawings.
 * Layers allow the AI and user to separate lineart, anatomy, shading, and accents.
 */
data class DrawingLayer(
    val id: String = java.util.UUID.randomUUID().toString(),
    val name: String = "Layer 1",
    val isVisible: Boolean = true,
    val isLocked: Boolean = false,
    val opacity: Float = 1.0f,
    val strokes: List<DrawingStroke> = emptyList(),
    val colorTagHex: String = "#00F0FF"
) {
    val totalPoints: Int get() = strokes.sumOf { it.points.size }
}

/**
 * Complete set of drawing instructions generated by Puter.js AI or synthesizers,
 * organized into performant state-based vector layers.
 */
data class ArtHaxInstructionSet(
    val id: String,
    val title: String,
    val prompt: String,
    val model: String,
    val strokes: List<DrawingStroke> = emptyList(),
    val layers: List<DrawingLayer> = if (strokes.isNotEmpty()) {
        listOf(
            DrawingLayer(
                id = "default_layer",
                name = "Main Vector Layer",
                strokes = strokes
            )
        )
    } else {
        emptyList()
    },
    val canvasAspectRatio: Float = 1.0f,
    val totalEstimatedPoints: Int = if (layers.isNotEmpty()) layers.sumOf { it.totalPoints } else strokes.sumOf { it.points.size },
    val generatedAtMillis: Long = System.currentTimeMillis()
) {
    /**
     * Aggregated list of visible active strokes across all enabled layers.
     */
    val activeStrokes: List<DrawingStroke>
        get() {
            return if (layers.isNotEmpty()) {
                layers.filter { it.isVisible }.flatMap { layer ->
                    if (layer.opacity < 0.99f) {
                        // Apply layer opacity into stroke colors
                        layer.strokes.map { stroke ->
                            val baseColor = stroke.parseColor()
                            val adjustedColor = baseColor.copy(alpha = baseColor.alpha * layer.opacity)
                            stroke.copy(colorHex = String.format("#%08X", (adjustedColor.value.toLong() and 0xFFFFFFFFL)))
                        }
                    } else {
                        layer.strokes
                    }
                }
            } else {
                strokes
            }
        }
}

